#!/usr/bin/env node
// UI design-system gate (docs/design/DESIGN-LANGUAGE.md §9).
// Ratchet: legacy files may keep their current debt but never add to it; files not in the
// baseline (all new code) must be clean. `--update` rewrites the baseline but refuses increases,
// so the recorded debt can only go down.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcRoot = path.join(repo, "apps/web/src");
const baselineFile = path.join(repo, "scripts/ui-baseline.json");
// Token and icon sources are where raw values are supposed to live.
const EXEMPT = new Set(["ui/tokens.css", "ui/icons.tsx"]);

const RULES = {
  hexColor: { label: "硬编码色值（改用 --g-* 令牌）", files: /\.(css|tsx?)$/, pattern: /#[0-9a-fA-F]{3,8}\b(?![-\w])/g, skipLine: /^\s*(\/\/|\*|\/\*)|url\(|href=|aria-|["'`]#\/|\bid=|location\.hash|#\{/ },
  inlineStyle: { label: "JSX 内联样式（改用 CSS 类）", files: /\.tsx$/, pattern: /style=\{\{/g },
  rawFontSize: { label: "非令牌字号（改用 --g-fs-*）", files: /\.css$/, pattern: /font-size:(?!\s*(?:var\(|inherit\b|100%|1em\b))[^;}]+/g },
  rawZIndex: { label: "非令牌层级（改用 --g-z-*）", files: /\.css$/, pattern: /z-index:\s*-?\d+/g },
  important: { label: "!important", files: /\.css$/, pattern: /!important/g },
};

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return /\.(css|tsx?)$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name) ? [full] : [];
  });
}

// A line may opt out with an explicit reason: `/* ui-allow: <why> */`. Reviewers check the reason.
const ALLOW = /ui-allow:\s*\S/;
function count(text, rule) {
  return text.split(/\r?\n/).reduce((sum, line) => {
    if (ALLOW.test(line) || rule.skipLine?.test(line)) return sum;
    return sum + (line.match(rule.pattern)?.length ?? 0);
  }, 0);
}

export function measure() {
  const result = {};
  for (const file of walk(srcRoot)) {
    const rel = path.relative(srcRoot, file).split(path.sep).join("/");
    if (EXEMPT.has(rel)) continue;
    const text = fs.readFileSync(file, "utf8");
    const counts = {};
    for (const [id, rule] of Object.entries(RULES)) {
      if (!rule.files.test(rel)) continue;
      const n = count(text, rule);
      if (n) counts[id] = n;
    }
    if (Object.keys(counts).length) result[rel] = counts;
  }
  return result;
}

function main() {
  const update = process.argv.includes("--update");
  const current = measure();
  const hasBaseline = fs.existsSync(baselineFile);
  const baseline = hasBaseline ? JSON.parse(fs.readFileSync(baselineFile, "utf8")).files ?? {} : {};
  const increases = [];
  // The very first --update records today's debt; after that the baseline may only go down.
  if (hasBaseline) for (const [file, counts] of Object.entries(current)) {
    for (const [id, n] of Object.entries(counts)) {
      const allowed = baseline[file]?.[id] ?? 0;
      if (n > allowed) increases.push({ file, id, n, allowed });
    }
  }
  const total = map => Object.values(map).reduce((sum, counts) => sum + Object.values(counts).reduce((a, b) => a + b, 0), 0);
  if (increases.length) {
    console.error(`UI 门禁未通过：${increases.length} 处新增违规（规则见 docs/design/DESIGN-LANGUAGE.md §9）`);
    for (const { file, id, n, allowed } of increases) console.error(`  apps/web/src/${file}  ${RULES[id].label}：${allowed} → ${n}`);
    if (update) console.error("已拒绝更新基线：基线只能下降。先修复上述违规。");
    process.exitCode = 1;
    return;
  }
  if (update) {
    const sorted = Object.fromEntries(Object.entries(current).sort(([a], [b]) => a.localeCompare(b)));
    fs.writeFileSync(baselineFile, `${JSON.stringify({ note: "UI debt ratchet. Generated by `pnpm check:ui --update`; counts may only go down.", files: sorted }, null, 2)}\n`);
    console.log(`基线已更新：${total(baseline)} → ${total(current)} 处遗留违规。`);
    return;
  }
  const paid = total(baseline) - total(current);
  console.log(`UI 门禁通过：无新增违规；遗留 ${total(current)} 处${paid > 0 ? `（比基线少 ${paid}，可运行 pnpm check:ui --update 锁定进展）` : ""}。`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();

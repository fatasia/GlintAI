import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { build } from "esbuild";
import { expect, it } from "vitest";
import { parseProject } from "../../../packages/scenescript/src/parse";
import { localChapterToolBuildOptions } from "./portable-service-build.mjs";
import { chapterLauncher } from "./portable-launcher.mjs";

it.runIf(process.platform === "win32")("runs the packaged local chapter tool without an HTTP or WebView session", async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "glint-local-chapters-"));
  const server = path.join(root, "app", "server"), cli = path.join(root, "app", "cli");
  const source = path.join(root, "素材源"), target = path.join(root, "素材目标"), files = path.join(root, "文档");
  for (const dir of [server, cli, source, target, files]) fs.mkdirSync(dir, { recursive: true });
  const repo = path.resolve(import.meta.dirname, "../../..");
  const bridge = process.env.GLINT_TEST_SECURE_BRIDGE ?? path.join(repo, "apps/desktop/secure-assets/target/debug/glint-secure-assets.exe");
  fs.copyFileSync(bridge, path.join(server, "glint-secure-assets.exe"));
  const entry = path.join(cli, "local-chapter-tool.mjs");
  await build(localChapterToolBuildOptions(repo, entry));
  const launcher = path.join(root, "Glint-chapters.cmd");
  fs.writeFileSync(launcher, chapterLauncher({ lite: false }));
  fs.copyFileSync(process.execPath, path.join(root, "node.exe"));
  const shellHelp = spawnSync("cmd.exe", ["/d", "/c", "Glint-chapters.cmd", "help"], { cwd: root, encoding: "utf8", windowsHide: true, timeout: 30000 });
  expect(shellHelp.status, shellHelp.stderr).toBe(0);
  expect(shellHelp.stdout).toContain("Glint");
  const png = spawnSync("ffmpeg", ["-v", "error", "-f", "lavfi", "-i", "color=c=red:s=16x16", "-frames:v", "1", "-f", "image2pipe", "-vcodec", "png", "pipe:1"], { windowsHide: true });
  expect(png.status, String(png.stderr)).toBe(0);
  fs.writeFileSync(path.join(source, "picture.png"), png.stdout);
  const chapters = ["one", "two"].map((id, index) => ({ title: `章节 ${id}`, updatedAt: index + 1,
    context: { mode: "source", text: `资料${id}`, template: "explainer", theme: "whiteboard", evidence: "依据" },
    project: parseProject({ schemaVersion: 1, id, title: id, aspect: "16:9", knowledgeSources: [], scenes: [{ id: "cover", kind: "image", src: "assets/picture.png", narration: { text: id, durationMs: 1500 } }] }) }));
  const refs = path.join(files, "章节.references.json"), bundle = path.join(files, "迁移包.json"), restored = path.join(files, "恢复.json");
  fs.writeFileSync(refs, JSON.stringify({ kind: "glint.chapters.references", version: 1, chapters }));
  const bomRefs = path.join(files, "带BOM.json");
  fs.writeFileSync(bomRefs, Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), fs.readFileSync(refs)]));
  const run = (...args: string[]) => spawnSync(process.execPath, [entry, ...args], { encoding: "utf8", windowsHide: true, timeout: 60000 });
  const command = (...args: string[]) => spawnSync("cmd.exe", ["/d", "/s", "/c", `""${launcher}" ${args.map(arg => `"${arg}"`).join(" ")}"`], { cwd: root, encoding: "utf8", windowsHide: true, windowsVerbatimArguments: true, timeout: 60000 });
  const exportArgs = ["export", "--chapters", refs, "--assets", source, "--out", bundle];
  const exported = command(...exportArgs); expect(exported.status, exported.stderr).toBe(0);
  const bomBundle = path.join(files, "带BOM迁移包.json"), bomTarget = path.join(root, "BOM目标");
  fs.mkdirSync(bomTarget);
  const bomExport = command("export", "--chapters", bomRefs, "--assets", source, "--out", bomBundle);
  expect(bomExport.status, bomExport.stderr).toBe(0);
  fs.writeFileSync(bomBundle, Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), fs.readFileSync(bomBundle)]));
  const bomPreview = command("preview", "--bundle", bomBundle, "--assets", bomTarget);
  expect(bomPreview.status, bomPreview.stderr).toBe(0);
  const bomHash = bomPreview.stdout.match(/确认摘要：([a-f0-9]{64})/)?.[1];
  expect(bomHash).toBe(createHash("sha256").update("glint-chapter-confirm-v1\0").update(path.win32.normalize(bomTarget)).update("\0").update(fs.readFileSync(bomBundle)).digest("hex"));
  expect(fs.readdirSync(bomTarget)).toEqual([]);
  const bomRestored = path.join(files, "BOM恢复.json");
  const bomRestore = command("restore", "--bundle", bomBundle, "--assets", bomTarget, "--out", bomRestored, "--confirm", bomHash!);
  expect(bomRestore.status, bomRestore.stderr).toBe(0);
  expect(JSON.parse(fs.readFileSync(bomRestored, "utf8")).chapters).toHaveLength(2);
  const invalidUtf8 = path.join(files, "invalid-utf8.json");
  fs.writeFileSync(invalidUtf8, Buffer.from([0xff]));
  expect(run("preview", "--bundle", invalidUtf8, "--assets", target).stderr).toContain("不是有效 UTF-8");
  const bytes = fs.readFileSync(bundle), hash = createHash("sha256").update("glint-chapter-confirm-v1\0").update(path.win32.normalize(target)).update("\0").update(bytes).digest("hex");
  expect(run(...exportArgs).status).toBe(0);
  const preview = run("preview", "--bundle", bundle, "--assets", target);
  expect(preview.status, preview.stderr).toBe(0); expect(preview.stdout).toContain(hash); expect(fs.readdirSync(target)).toEqual([]);
  const restoreArgs = ["restore", "--bundle", bundle, "--assets", target, "--out", restored, "--confirm", hash];
  expect(run(...restoreArgs.slice(0, -1), "0".repeat(64)).status).not.toBe(0);
  const otherTarget = path.join(root, "另一目标"); fs.mkdirSync(otherTarget);
  const wrongDestination = run("restore", "--bundle", bundle, "--assets", otherTarget, "--out", restored, "--confirm", hash);
  expect(wrongDestination.status).not.toBe(0);
  expect(wrongDestination.stderr).toContain("目标素材目录不一致");
  expect(fs.readdirSync(otherTarget)).toEqual([]);
  expect(fs.readdirSync(target)).toEqual([]);
  fs.writeFileSync(restored, "do not overwrite");
  expect(run(...restoreArgs).status).not.toBe(0); expect(fs.readFileSync(restored, "utf8")).toBe("do not overwrite");
  expect(fs.readdirSync(target)).toEqual([]);
  const alternate = path.join(files, "恢复成功.json"); restoreArgs[6] = alternate;
  const committed = run(...restoreArgs); expect(committed.status, committed.stderr).toBe(0);
  const result = JSON.parse(fs.readFileSync(alternate, "utf8"));
  expect(result.kind).toBe("glint.chapters.references");
  expect(result.chapters.map(({ title, updatedAt, context }: typeof chapters[number]) => ({ title, updatedAt, context }))).toEqual(chapters.map(({ title, updatedAt, context }) => ({ title, updatedAt, context })));
  const assetName = result.chapters[0].project.scenes[0].src.slice(7);
  expect(fs.readFileSync(path.join(target, assetName))).toEqual(png.stdout);
  const nested = structuredClone(chapters);
  nested[0]!.project.theme = { backgroundImage: "assets/picture.png" };
  const nestedRefs = path.join(files, "nested.json"), nestedBundle = path.join(files, "nested-bundle.json");
  fs.writeFileSync(nestedRefs, JSON.stringify({ kind: "glint.chapters.references", version: 1, chapters: nested }));
  const nestedExport = run("export", "--chapters", nestedRefs, "--assets", source, "--out", nestedBundle);
  expect(nestedExport.status).not.toBe(0); expect(nestedExport.stderr).toContain("无法迁移的素材引用");
  expect(fs.existsSync(nestedBundle)).toBe(false);
  expect(run(...restoreArgs).status).toBe(0);
  expect(fs.readFileSync(refs, "utf8")).toContain("资料one");
  const corrupt = JSON.parse(bytes.toString()); corrupt.chapters[0].assets[0].sha256 = "0".repeat(64);
  const bad = path.join(files, "损坏.json"); fs.writeFileSync(bad, JSON.stringify(corrupt));
  expect(run("preview", "--bundle", bad, "--assets", target).status).not.toBe(0);
  fs.writeFileSync(path.join(target, assetName), "foreign");
  expect(run(...restoreArgs).status).not.toBe(0);
  expect(fs.readFileSync(path.join(target, assetName), "utf8")).toBe("foreign");
  // Keep the exclusively created fixture for inspection; do not delete user data.
}, 120000);

it.runIf(process.platform === "win32")("binds confirmation to the selected destination without touching unrelated data", async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "glint-chapter-text-only-"));
  const server = path.join(root, "app", "server"), cli = path.join(root, "app", "cli");
  const source = path.join(root, "source"), target = path.join(root, "target"), other = path.join(root, "other"), files = path.join(root, "files");
  for (const dir of [server, cli, source, target, other, files]) fs.mkdirSync(dir, { recursive: true });
  const repo = path.resolve(import.meta.dirname, "../../..");
  fs.copyFileSync(process.env.GLINT_TEST_SECURE_BRIDGE ?? path.join(repo, "apps/desktop/secure-assets/target/debug/glint-secure-assets.exe"), path.join(server, "glint-secure-assets.exe"));
  const entry = path.join(cli, "local-chapter-tool.mjs");
  await build(localChapterToolBuildOptions(repo, entry));
  fs.writeFileSync(path.join(root, "Glint-chapters.cmd"), chapterLauncher({ lite: false }), { flag: "wx" });
  fs.copyFileSync(process.execPath, path.join(root, "node.exe"), fs.constants.COPYFILE_EXCL);
  const shellHelp = spawnSync("cmd.exe", ["/d", "/c", "Glint-chapters.cmd", "help"], { cwd: root, encoding: "utf8", windowsHide: true, timeout: 30000 });
  expect(shellHelp.status, shellHelp.stderr).toBe(0);
  expect(shellHelp.stdout).toContain("%APPDATA%\\ai.glint.desktop.dev\\media");
  const chapters = ["one", "two"].map(id => ({ title: `章节 ${id}`, updatedAt: 1,
    context: { mode: "source", text: "", template: "explainer", theme: "whiteboard", evidence: "" },
    project: parseProject({ schemaVersion: 1, id, title: id, aspect: "16:9", knowledgeSources: [], scenes: [{ id: "intro", kind: "title", title: id, narration: { text: id, durationMs: 1000 } }] }) }));
  const refs = path.join(files, "refs.json"), bundle = path.join(files, "bundle.json"), restored = path.join(files, "restored.json");
  fs.writeFileSync(refs, JSON.stringify({ kind: "glint.chapters.references", version: 1, chapters }), { flag: "wx" });
  const run = (...args: string[]) => spawnSync(process.execPath, [entry, ...args], { encoding: "utf8", windowsHide: true, timeout: 30000 });
  const exportArgs = ["export", "--chapters", refs, "--assets", source, "--out", bundle];
  expect(run(...exportArgs).status).toBe(0);
  const preview = run("preview", "--bundle", bundle, "--assets", target, "--out", restored);
  expect(preview.status, preview.stderr).toBe(0);
  expect(preview.stdout).toContain(target);
  expect(preview.stdout).toContain("已检查输出文件");
  expect(fs.existsSync(restored)).toBe(false);
  expect(run("preview", "--bundle", bundle, "--assets", target).stdout).toContain("未检查输出文件");
  expect(run("preview", "--bundle", bundle, "--assets", target, "--out", restored, "--out", restored).status).not.toBe(0);
  expect(run("preview", "--bundle", bundle, "--out", restored).status).not.toBe(0);
  expect(run("preview", "--bundle", bundle, "--assets", target, "--out", path.join(root, "missing", "output.json")).status).not.toBe(0);
  const confirm = preview.stdout.match(/确认摘要：([a-f0-9]{64})/)?.[1];
  expect(confirm).toBeDefined();
  const restore = (destination: string, hash: string) => run("restore", "--bundle", bundle, "--assets", destination, "--out", restored, "--confirm", hash);
  expect(restore(other, confirm!).stderr).toContain("目标素材目录不一致");
  expect(fs.existsSync(restored)).toBe(false);
  expect(fs.readdirSync(other)).toEqual([]);
  expect(restore(target, "0".repeat(64)).status).not.toBe(0);
  const originalBundle = fs.readFileSync(bundle, "utf8");
  fs.writeFileSync(bundle, originalBundle + " ");
  expect(restore(target, confirm!).stderr).toContain("目标素材目录不一致");
  expect(fs.existsSync(restored)).toBe(false);
  fs.writeFileSync(bundle, originalBundle);
  fs.writeFileSync(restored, "existing", { flag: "wx" });
  const conflictPreview = run("preview", "--bundle", bundle, "--assets", target, "--out", restored);
  expect(conflictPreview.status).not.toBe(0);
  expect(conflictPreview.stderr).toContain("输出文件已存在且内容不同");
  expect(fs.readFileSync(restored, "utf8")).toBe("existing");
  expect(fs.readdirSync(target)).toEqual([]);
  expect(restore(target, confirm!).status).not.toBe(0);
  expect(fs.readFileSync(restored, "utf8")).toBe("existing");
  const valid = path.join(files, "valid.json");
  const args = ["restore", "--bundle", bundle, "--assets", target, "--out", valid, "--confirm", confirm!];
  expect(run(...args).status).toBe(0);
  expect(JSON.parse(fs.readFileSync(valid, "utf8")).chapters).toEqual(chapters);
  expect(run(...args).status).toBe(0);
  const identicalPreview = run("preview", "--bundle", bundle, "--assets", target, "--out", valid);
  expect(identicalPreview.status, identicalPreview.stderr).toBe(0);
  expect(identicalPreview.stdout).toContain(confirm);
  expect(fs.readdirSync(target)).toEqual([]);
  expect(run("help").stdout).toContain("%APPDATA%\\ai.glint.desktop.dev\\media");
}, 120000);

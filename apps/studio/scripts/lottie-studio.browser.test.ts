import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawn, spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";
import puppeteer from "puppeteer-core";
import { expect, it } from "vitest";
import { findSystemBrowser } from "./direct-browser/host";
import { readImportedLottie } from "./lottie-import";
import { parseProject } from "@glintai/scenescript";

it.skipIf(process.env.GLINT_BROWSER_UI_TEST !== "1")("opens the real local entry, edits safely, detects conflicts, and rejects cross-origin requests", async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "glint-motion-studio-"));
  const examples = JSON.parse(fs.readFileSync(fileURLToPath(new URL("../../../examples/local-media/readiness.scenescript.json", import.meta.url)), "utf8"));
  const scene = examples.scenes.find((item: { animation?: string }) => item.animation === "lottie");
  const animation = JSON.parse(scene.html.match(/window\.__glintLottie=([\s\S]*);<\/script>/)[1]);
  animation.layers[0].ks.o = { a: 0, k: 100 };
  animation.layers[0].ks.a = { a: 0, k: [12, 34, 56] };
  animation.layers.push({ ...structuredClone(animation.layers[0]), ind: 2, nm: "Second" });
  animation.layers[1].ks.a = { a: 1, k: [{ t: 0, s: [12, 34, 56] }, { t: 12, s: [20, 30, 56] }] };
  const project = path.join(root, "project.json"), source = path.join(root, "source.json");
  fs.writeFileSync(project, JSON.stringify({ schemaVersion: 1, id: "p", title: "P", aspect: "16:9", fps: 24, knowledgeSources: [], scenes: [{ id: "first", kind: "title", title: "Start", narration: { text: "Start", durationMs: 1000 } }] }));
  fs.writeFileSync(source, JSON.stringify(animation));
  const original = fs.readFileSync(project), originalSource = fs.readFileSync(source);
  const cli = fileURLToPath(new URL("./glint.ts", import.meta.url));
  const tsx = pathToFileURL(createRequire(import.meta.url).resolve("tsx/esm")).href;
  const env = { ...process.env, HOME: root, USERPROFILE: root, APPDATA: root, LOCALAPPDATA: root, TEMP: root, TMP: root, GLINT_CACHE_DIR: path.join(root, "cache") };
  const child = spawn(process.execPath, ["--import", tsx, cli, "lottie-studio", `--project=${project}`, "--scene=motion", `--source=${source}`], { cwd: root, env, stdio: ["ignore", "pipe", "pipe"] });
  let output = "";
  child.stdout.on("data", data => { output += data; });
  child.stderr.on("data", data => { output += data; });
  let browser: Awaited<ReturnType<typeof puppeteer.launch>> | undefined;
  try {
    const end = Date.now() + 30000;
    while (!/http:\/\/127\.0\.0\.1:\d+\/#\w+/.test(output) && child.exitCode === null && Date.now() < end) await new Promise(resolve => setTimeout(resolve, 100));
    const url = output.match(/http:\/\/127\.0\.0\.1:\d+\/#\w+/)?.[0];
    expect(url, output).toBeTruthy();
    const base = url!.split("/#")[0]!, token = url!.split("#")[1]!;
    expect((await fetch(`${base}/api/state`)).status).toBe(403);
    expect((await fetch(`${base}/api/state`, { headers: { "x-glint-token": token, origin: "https://attacker.example" } })).status).toBe(403);
    const state = await (await fetch(`${base}/api/state`, { headers: { "x-glint-token": token } })).json() as { revision: string };
    const save = (data: unknown) => fetch(`${base}/api/save`, { method: "POST", headers: { "x-glint-token": token, "content-type": "application/json" }, body: JSON.stringify(data) });
    expect((await save({ output: "../escape.json", edits: {}, revision: state.revision })).status).toBe(400);
    expect((await save({ output: "bad.json", edits: { evil: "x" }, revision: state.revision })).status).toBe(400);
    browser = await puppeteer.launch({ executablePath: findSystemBrowser(), headless: true, userDataDir: path.join(root, "browser") });
    const page = await browser.newPage();
    await page.setViewport({ width: 1280, height: 800 });
    await page.goto(url!, { waitUntil: "domcontentloaded" });
    await page.waitForSelector(".layer");
    expect(await page.$eval('#empty-text', el => (el as HTMLInputElement).disabled)).toBe(true);
    await page.click(".layer");
    expect(await page.$eval('input[name="layer-pos"]', el => (el as HTMLInputElement).disabled)).toBe(true);
    expect(await page.$eval('input[name="layer-anchor"]', el => (el as HTMLInputElement).disabled)).toBe(false);
    expect(await page.$eval('#selected', el => el.textContent)).toContain('锚点 12,34,56');
    expect(await page.$eval('input[name="layer-opacity"]', el => (el as HTMLInputElement).disabled)).toBe(false);
    expect(await page.$eval('input[name="layer-text"]', el => (el as HTMLInputElement).disabled)).toBe(true);
    expect(await page.$eval('select[name="position-keyframe"]', el => (el as HTMLSelectElement).disabled)).toBe(false);
    expect(await page.$eval('select[name="position-keyframe"]', el => Array.from(el.options).slice(1).map(option => option.textContent))).toEqual(["帧 0 · 位置 260,250,0", "帧 12 · 位置 540,250,0"]);
    if (process.env.GLINT_MOTION_EVIDENCE) await page.screenshot({ path: path.join(process.env.GLINT_MOTION_EVIDENCE, "round-1-desktop.png") });
    await page.type('input[name="layer-opacity"]', "25");
    await page.type('input[name="layer-anchor"]', "-40,60");
    await page.select('select[name="position-keyframe"]', "0");
    await page.type('input[name="keyframe-pos"]', "300,140");
    page.once("dialog", dialog => dialog.dismiss());
    await page.click('.layer[data-index="1"]');
    expect(await page.$eval('input[name="layer-opacity"]', el => (el as HTMLInputElement).value)).toBe("25");
    expect(await page.$eval('input[name="layer-anchor"]', el => (el as HTMLInputElement).value)).toBe("-40,60");
    await page.click('button[type="submit"]');
    await page.waitForFunction(() => document.querySelector("#status")?.textContent?.includes("已保存"));
    const result = parseProject(JSON.parse(fs.readFileSync(path.join(root, "motion-edited.json"), "utf8"))).scenes.find(item => item.id === "motion")!;
    if (result.kind !== "html") throw new Error("Expected imported Lottie");
    expect((readImportedLottie(result).source.layers[0] as any).ks.o.k).toBe(25);
    expect((readImportedLottie(result).source.layers[0] as any).ks.a.k).toEqual([-40, 60, 56]);
    expect((readImportedLottie(result).source.layers[0] as any).ks.p.k[0].s).toEqual([300, 140, 0]);
    expect((readImportedLottie(result).source.layers[0] as any).ks.p.k[0].e).toEqual([540, 250, 0]);
    expect((readImportedLottie(result).source.layers[1] as any).ks.a).toEqual(animation.layers[1].ks.a);
    expect((await save({ output: "bad-position.json", edits: { "layer-index": "0", "position-keyframe": "1", "keyframe-pos": "1," }, revision: state.revision })).status).toBe(400);
    expect(fs.existsSync(path.join(root, "bad-position.json"))).toBe(false);
    page.once("dialog", dialog => dialog.accept());
    await page.click('.layer[data-index="1"]');
    expect(await page.$eval('input[name="layer-anchor"]', el => (el as HTMLInputElement).disabled)).toBe(true);
    expect(await page.$eval('#selected', el => el.textContent)).toContain('锚点 不可编辑');
    expect((await save({ output: "animated-anchor.json", edits: { "layer-index": "1", "layer-anchor": "1,2" }, revision: state.revision })).status).toBe(400);
    expect(fs.existsSync(path.join(root, "animated-anchor.json"))).toBe(false);
    expect((await save({ output: "bad-anchor.json", edits: { "layer-index": "0", "layer-anchor": "1," }, revision: state.revision })).status).toBe(400);
    expect(fs.existsSync(path.join(root, "bad-anchor.json"))).toBe(false);
    expect(fs.readFileSync(project)).toEqual(original); expect(fs.readFileSync(source)).toEqual(originalSource);
    const movie = path.join(root, "result.mp4");
    const rendered = spawnSync(process.execPath, ["--import", tsx, cli, "render-native", `--project=${path.join(root, "motion-edited.json")}`, "--scenes=motion", `--out=${movie}`, "--fast", "--no-cache", "--tts=mock", "--music=off"], { cwd: root, env: { ...process.env, GLINT_CACHE_DIR: path.join(root, "cache") }, encoding: "utf8", timeout: 120000 });
    expect(rendered.status, rendered.stderr + rendered.stdout).toBe(0);
    expect(fs.statSync(movie).size).toBeGreaterThan(1000);
    await page.screenshot({ path: path.join(root, "desktop.png") });
    if (process.env.GLINT_MOTION_EVIDENCE) await page.screenshot({ path: path.join(process.env.GLINT_MOTION_EVIDENCE, "round-2-desktop.png") });
    await page.setViewport({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: path.join(root, "mobile.png") });
    if (process.env.GLINT_MOTION_EVIDENCE) await page.screenshot({ path: path.join(process.env.GLINT_MOTION_EVIDENCE, "round-2-mobile.png") });
    await page.click('button[type="submit"]');
    await page.waitForFunction(() => document.querySelector("#status")?.classList.contains("error"));
    fs.writeFileSync(source, JSON.stringify({ ...animation, w: animation.w + 1 }));
    expect((await save({ output: "conflict.json", edits: {}, revision: state.revision })).status).toBe(409);
    expect(fs.existsSync(path.join(root, "conflict.json"))).toBe(false);
  } finally {
    await browser?.close();
    child.kill();
    await new Promise<void>(resolve => { if (child.exitCode !== null) resolve(); else { child.once("exit", () => resolve()); setTimeout(resolve, 3000); } });
    try { fs.rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }); } catch (error) { console.warn("无法清理隔离测试目录", root, error); }
  }
}, 180000);
